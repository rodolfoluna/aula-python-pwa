test('guardado conserva cambios escritos durante una petición y detecta conflictos de revisión', async () => {
  const memory = new Map(), storage = { getItem: key => memory.get(key), setItem: (key, value) => memory.set(key, value), removeItem: key => memory.delete(key) };
  let resolveSave, calls = 0;
  const sync = new DraftSync({ key: 'answer', answer: { value: 0 }, revision: 0, storage, save: async () => { calls++; return new Promise(resolve => { resolveSave = resolve; }); } });
  sync.set({ value: 1 }); const pending = sync.flush(); await Promise.resolve(); sync.set({ value: 2 }); resolveSave({ revision: 1 }); await pending;
  assert.equal(sync.dirty, true); assert.equal(sync.answer.value, 2); assert.equal(JSON.parse(memory.get('answer')).revision, 1);
  const recovered = new DraftSync({ key: 'answer', answer: { value: 1 }, revision: 1, storage, save: async () => ({ revision: 2 }) }); assert.equal(recovered.answer.value, 2); await recovered.flush(); assert.equal(memory.has('answer'), false);
  recovered.set({ value: 3 }); recovered.saveRequest = async () => { throw Object.assign(new Error('Conflicto'), { status: 409 }); };
  await assert.rejects(recovered.flush(), /Conflicto/); assert.equal(recovered.conflict, true); assert.equal(memory.has('answer'), true); assert.equal(calls, 1);
});

test('revisión: notas válidas, devolución individual, historial y nueva entrega', async () => {
  const store = memoryAccountStore(), now = Date.now();
  const teacher = await store.createUser({ email: 'reviewer@example.com', password: 'SoloPrueba123456', role: 'teacher', name: 'Docente' });
  const other = await store.createUser({ email: 'other@example.com', password: 'SoloPrueba123456', role: 'teacher', name: 'Otro' });
  const student = await store.createUser({ email: 'reviewstudent@example.com', password: 'SoloPrueba123456', role: 'student', teacherId: teacher.id, control: '003', name: 'Ana' });
  await store.updateProfile(student.id, { must_change_password: false }); student.must_change_password = false;
  const group = await store.createGroup(teacher.id, 'A'); await store.setMembership(group.id, student.id, true);
  const service = createActivitiesService(store, () => now), draft = await service.saveActivity(teacher, newActivity());
  const [assignment] = await service.assign(teacher, { activityId: draft.id, version: 1, groupIds: [group.id], dueAt: new Date(now + 1000).toISOString() });
  const opened = await service.open(student, assignment.id), data = { assignmentId: assignment.id, studentId: student.id, revision: 1, action: 'review', grade: 0, feedback: 'Revisa la suma.' };
  await assert.rejects(service.review(teacher, data), /debe entregar/);
  await service.saveAnswer(student, { assignmentId: assignment.id, revision: 0, answer: opened.answer, submit: true });
  await assert.rejects(service.review(student, data), /Solo el profesor/);
  await assert.rejects(service.review(other, data), /sin acceso/);
  for (const grade of [-1, 101, NaN, Infinity, '90', 1.234]) await assert.rejects(service.review(teacher, { ...data, grade }), /calificación/);
  await service.review(teacher, data);
  let state = await service.open(student, assignment.id); assert.equal(state.submission.grade, 0); assert.equal(state.writable, false); assert.equal(state.reviews.length, 1);
  await assert.rejects(service.review(teacher, data), /cambió/);
  const correctionDueAt = new Date(now + 86400000).toISOString();
  await assert.rejects(service.review(teacher, { ...data, revision: 2, action: 'return', feedback: '', correctionDueAt }), /qué corregir/);
  const returned = await service.review(teacher, { ...data, revision: 2, action: 'return', correctionDueAt });
  const afterDeadline = createActivitiesService(store, () => now + 5000);
  state = await afterDeadline.open(student, assignment.id); assert.equal(state.writable, true); assert.equal(state.reviews.length, 2);
  state.answer.cells[1].code = 'print("corregido")';
  await afterDeadline.saveAnswer(student, { assignmentId: assignment.id, revision: 3, answer: state.answer, submit: true });
  const old = await service.reviewHistory(student, { assignmentId: assignment.id, reviewId: returned.review_id, studentId: other.id });
  assert.notEqual(old.review.answer.cells[1].code, state.answer.cells[1].code);
  await assert.rejects(service.reviewHistory(other, { assignmentId: assignment.id, reviewId: returned.review_id, studentId: student.id }), /sin acceso/);
  await service.review(teacher, { ...data, revision: 4, grade: 95.5, feedback: 'Ahora sí.' });
  state = await service.open(student, assignment.id); assert.equal(state.submission.grade, 95.5); assert.equal(state.writable, false);
  await service.close(teacher, { assignmentId: assignment.id, closed: true });
  await assert.rejects(service.review(teacher, { ...data, revision: 5, action: 'return', correctionDueAt }), /Reabre/);
});


test('proyecto compartido se guarda por delta y solo su profesor elimina la asignación', async () => {
  const { projectWorkspace, normalizeActivity, newExercise } = await import('../dist/activity-model.js');
  const { answerPatch } = await import('../dist/answer-patch.js');
  const store = memoryAccountStore();
  const teacher = await store.createUser({ email: 'project@example.com', password: 'PruebaTemporal123', role: 'teacher', name: 'Docente' });
  const other = await store.createUser({ email: 'foreign@example.com', password: 'PruebaTemporal123', role: 'teacher', name: 'Otro' });
  const student = await store.createUser({ email: 'projectstudent@example.com', password: 'PruebaTemporal123', role: 'student', teacherId: teacher.id, control: '010', name: 'Ana' });
  const group = await store.createGroup(teacher.id, 'A'); await store.setMembership(group.id, student.id, true);
  const service = createActivitiesService(store), legacy = newActivity('files');
  legacy.content.exercises.push(newExercise());
  legacy.content.exercises[0].files['base.py'] = 'VALUE = 42'; legacy.content.exercises[0].lockedFiles.push('base.py');
  const draft = await service.saveActivity(teacher, legacy);
  const [assignment] = await service.assign(teacher, { activityId: draft.id, version: 1, groupIds: [group.id] });
  const before = initialAnswer(legacy);
  await service.saveAnswer(student, { assignmentId: assignment.id, revision: 0, answer: before, submit: false });
  const workspace = projectWorkspace(legacy, before), after = { project: { files: workspace.files, entry: workspace.entry } };
  after.project.files['main.py'] = 'from base import VALUE';
  await service.saveAnswer(student, { assignmentId: assignment.id, revision: 1, patch: answerPatch(before, after), requestId: crypto.randomUUID(), submit: false });
  assert.deepEqual((await service.open(student, assignment.id)).answer, after);
  const bad = structuredClone(after); delete bad.project.files['base.py'];
  assert.throws(() => validateAnswer(legacy, bad), /bloqueado/);
  const sharedTemplate = normalizeActivity({ ...legacy, content: { exercises: legacy.content.exercises, project: projectWorkspace(legacy) } });
  assert.equal(sharedTemplate.content.exercises[0].files, undefined);
  assert.doesNotThrow(() => validateAnswer(sharedTemplate, initialAnswer(sharedTemplate)));
  await assert.rejects(service.deleteAssignment(student, { assignmentId: assignment.id }), /profesor/);
  await assert.rejects(service.deleteAssignment(other, { assignmentId: assignment.id }), /acceso/);
  await service.deleteAssignment(teacher, { assignmentId: assignment.id });
  await assert.rejects(service.open(student, assignment.id), /acceso/);
  assert.equal((await store.listActivities(teacher.id)).length, 1);
  assert.equal(await store.submission(assignment.id, student.id), undefined);
});


test('el profesor adelanta y retrasa plazos sin alterar entregas, plantillas ni cierres', async () => {
  let now = Date.now(); const store = memoryAccountStore();
  const teacher = await store.createUser({ email: 'deadline@example.com', password: 'PruebaTemporal123', role: 'teacher', name: 'Docente' });
  const other = await store.createUser({ email: 'deadlineother@example.com', password: 'PruebaTemporal123', role: 'teacher', name: 'Otro' });
  const student = await store.createUser({ email: 'deadlinestudent@example.com', password: 'PruebaTemporal123', role: 'student', teacherId: teacher.id, control: '011', name: 'Ana' });
  const group = await store.createGroup(teacher.id, 'A'); await store.setMembership(group.id, student.id, true);
  const service = createActivitiesService(store, () => now), activity = await service.saveActivity(teacher, newActivity());
  const originalDue = new Date(now + 10000).toISOString();
  const [assignment] = await service.assign(teacher, { activityId: activity.id, version: 1, groupIds: [group.id], dueAt: originalDue });
  const draft = await service.open(student, assignment.id); draft.answer.cells[1].code = 'print(42)';
  await service.saveAnswer(student, { assignmentId: assignment.id, answer: draft.answer, revision: 0, submit: false });
  const before = await store.submission(assignment.id, student.id), snapshot = (await store.assignment(assignment.id)).snapshot;
  now += 20000; assert.equal((await service.open(student, assignment.id)).writable, false);
  const dueAt = new Date(now + 86400000).toISOString();
  await assert.rejects(service.setDeadline(student, { assignmentId: assignment.id, dueAt }), /profesor/);
  await assert.rejects(service.setDeadline(other, { assignmentId: assignment.id, dueAt }), /acceso/);
  for (const value of [null, '', 'incorrecta']) await assert.rejects(service.setDeadline(teacher, { assignmentId: assignment.id, dueAt: value }), /válidas/);
  await service.setDeadline(teacher, { assignmentId: assignment.id, dueAt });
  assert.equal((await service.open(student, assignment.id)).writable, true);
  assert.equal((await store.assignment(assignment.id)).due_at, dueAt);
  assert.deepEqual(await store.submission(assignment.id, student.id), before);
  assert.deepEqual((await store.assignment(assignment.id)).snapshot, snapshot);
  assert.deepEqual(await store.activity(activity.id), activity);
  await service.setDeadline(teacher, { assignmentId: assignment.id, dueAt });
  const earlier = new Date(now + 10000).toISOString();
  await service.setDeadline(teacher, { assignmentId: assignment.id, dueAt: earlier });
  assert.equal((await store.assignment(assignment.id)).due_at, earlier);
  assert.equal((await service.open(student, assignment.id)).writable, true);
  const past = new Date(now - 10000).toISOString();
  await service.setDeadline(teacher, { assignmentId: assignment.id, dueAt: past });
  assert.equal((await store.assignment(assignment.id)).due_at, past);
  assert.equal((await service.open(student, assignment.id)).writable, false);
  await service.setDeadline(teacher, { assignmentId: assignment.id, dueAt });
  assert.deepEqual(await store.submission(assignment.id, student.id), before);
  const later = new Date(now + 2 * 86400000).toISOString();
  const setDeadline = store.setAssignmentDeadline; store.setAssignmentDeadline = async () => null;
  await assert.rejects(service.setDeadline(teacher, { assignmentId: assignment.id, dueAt: later }), error => error.status === 409);
  store.setAssignmentDeadline = setDeadline;
  await service.saveAnswer(student, { assignmentId: assignment.id, answer: before.answer, revision: before.revision, submit: true });
  const submitted = await store.submission(assignment.id, student.id);
  await service.setDeadline(teacher, { assignmentId: assignment.id, dueAt: later });
  assert.equal((await service.open(student, assignment.id)).writable, false);
  assert.deepEqual(await store.submission(assignment.id, student.id), submitted);
  await service.close(teacher, { assignmentId: assignment.id, closed: true });
  await service.setDeadline(teacher, { assignmentId: assignment.id, dueAt: new Date(now + 3 * 86400000).toISOString() });
  assert.equal((await store.assignment(assignment.id)).closed, true);
  assert.equal(await store.setAssignmentDeadline(assignment.id, teacher.id, originalDue, later), null, 'No sobrescribe otro cambio de fecha con datos anteriores');
  const secondGroup = await store.createGroup(teacher.id, 'B');
  const [unlimited] = await service.assign(teacher, { activityId: activity.id, version: 1, groupIds: [secondGroup.id] });
  await service.setDeadline(teacher, { assignmentId: unlimited.id, dueAt: later });
  assert.equal((await store.assignment(unlimited.id)).due_at, later);
});
